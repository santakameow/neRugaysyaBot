// Детектор русского мата с упором на минимум false positive (порт с Python).
//
// Схема двухступенчатая:
//  1. нормализация токена (регистр, гомоглифы, повторы) — ловим обфускацию;
//  2. корневые регэкспы, заточенные так, чтобы НЕ цеплять приличные слова,
//     плюс маленький белый список на оставшиеся ловушки.
//
// Движок regexp в Go — это RE2: нет lookbehind/lookahead и backreference.
// В паттернах их нет; схлопывание повторов сделано вручную по рунам.
//
// Запуск демо:  go run profanity.go
// Для использования как библиотеки — вынесите функции в свой пакет,
// оставив экспортируемые FindProfanity / IsProfane / Censor.
package main

import (
	"regexp"
	"strings"
)

// --- 1. Нормализация (борьба с обфускацией) --------------------------------

// латиница / цифры / символы -> кириллица (только то, что встречается в корнях)
var homoglyphs = map[rune]rune{
	'a': 'а', 'e': 'е', 'o': 'о', 'p': 'р', 'c': 'с', 'x': 'х', 'y': 'у',
	'k': 'к', 'b': 'б', 'm': 'м', 't': 'т',
	'@': 'а', '0': 'о', '3': 'з', '4': 'ч', '6': 'б',
}

var nonCyrillic = regexp.MustCompile(`[^а-яё]`)

func normalize(token string) string {
	// нижний регистр + гомоглифы
	var b strings.Builder
	for _, r := range strings.ToLower(token) {
		if repl, ok := homoglyphs[r]; ok {
			b.WriteRune(repl)
		} else {
			b.WriteRune(r)
		}
	}
	// выкидываем всё, кроме кириллицы
	s := nonCyrillic.ReplaceAllString(b.String(), "")
	// схлопываем повторы: хуууй -> хуй (RE2 не умеет backreference — делаем вручную)
	return collapseRepeats(s)
}

func collapseRepeats(s string) string {
	var b strings.Builder
	var prev rune = -1
	for _, r := range s {
		if r != prev {
			b.WriteRune(r)
			prev = r
		}
	}
	return b.String()
}

// --- 2. Корневые паттерны (проверяем по НОРМАЛИЗОВАННОМУ токену) ------------

var roots = compileAll(
	// ---- ядро мата ----

	// ху*: 'ху' + {й,ё,я,е,и} в приличных словах почти не встречается
	// (худой/хутор/хунта/хула/хук/хурма/хуже/Хуан идут на другие буквы).
	// 'хую' — единственная ловушка (сухую, плохую, тихую), см. белый список.
	`ху[йёяеи]`,
	`хую`,

	// пизд* / пизж* (спизжено) / пезд*
	`пизд`, `пизж`, `пезд`,

	// еб*/ёб*: самый коварный корень. Берём только:
	//   - слово, НАЧИНАЮЩЕЕСЯ на еб/ёб (приличных таких нет);
	//   - конкретная приставка + еб/ёб (объеб, разъеб, съеб, наеб, ...);
	//   - долбоёб.
	// Так НЕ ловим: хлеб, треб(овать), греб, зебра, ребёнок, серебро,
	// амёба, нёбо, себе, объезд, разъезд, победа, поезд, наездник.
	`^[её]б`,
	`^(?:за|на|вы|до|по|пере|при|про|разъ?|съ|отъ?|объ?|подъ?|въ|у|недо)[её]б`,
	`долбо[её]б`,

	// блядь / блять / блядский; «бля» — ТОЛЬКО как целое слово
	// (иначе ловим рубля, корабля, оглобля, грабли).
	`бляд`, `блят`, `^бля+$`,

	// ---- прочая обсценная лексика (можно отключить) ----

	// муда*/мудил/мудоз — но НЕ мудрый, изумруд, Бермуды, талмуд
	`муда[кч]`, `мудач`, `мудил`, `мудо[звбё]`,

	// залупа
	`залуп`,

	// сука/сучка — с якорем ^, чтобы не поймать барсук(а/и/у)
	`^сук[аиоуеёй]`, `^суч(?:ий|ье|ка|ку|ки|ар|ён|онок)`, `^сукин`,

	// пидор/пидар/педераст/педрила («педик» НЕ берём из-за педикюра)
	`пид[оа]р`, `пидр`, `педераст`, `педрил`,

	// гондон / гандон
	`г[ао]ндон`,

	// шлюха / шлюшка
	`шлюх`, `шлюш`,

	// дроч* (исключение — дрочёна/драчёна, кушанье, см. белый список)
	`дроч`,
)

// белый список: гасит совпадения по веткам 'хую' и 'дроч'
var whitelist = regexp.MustCompile(`(?:су|глу|ветх|ли|пло|ти)хую$|дроч[её]на$`)

// границы токенов: латиница, кириллица, цифры, @ — чтобы обфускация не билась на части
var tokenRe = regexp.MustCompile(`[a-zA-Zа-яёА-ЯЁ0-9@]+`)

func compileAll(patterns ...string) []*regexp.Regexp {
	out := make([]*regexp.Regexp, len(patterns))
	for i, p := range patterns {
		out[i] = regexp.MustCompile(p)
	}
	return out
}

func matchesRoot(tok string) bool {
	for _, rx := range roots {
		if rx.MatchString(tok) {
			return true
		}
	}
	return false
}

// --- 3. Публичный интерфейс -------------------------------------------------

// FindProfanity возвращает найденные матерные слова в ИСХОДНОМ виде.
func FindProfanity(text string) []string {
	var hits []string
	for _, m := range tokenRe.FindAllString(text, -1) {
		tok := normalize(m)
		if tok == "" {
			continue
		}
		if matchesRoot(tok) && !whitelist.MatchString(tok) {
			hits = append(hits, m)
		}
	}
	return hits
}

func IsProfane(text string) bool {
	return len(FindProfanity(text)) > 0
}

// Censor заменяет матерные слова на mask.
func Censor(text, mask string) string {
	return tokenRe.ReplaceAllStringFunc(text, func(m string) string {
		tok := normalize(m)
		if tok != "" && matchesRoot(tok) && !whitelist.MatchString(tok) {
			return mask
		}
		return m
	})
}

